"""Matched TRAIN-only curvature sampling. No model or evaluation access."""
import cv2
import numpy as np

HEIGHT, WIDTH, SOURCE_HEIGHT = 640, 512, 1280


def displacement(amplitude, period, phase):
    if amplitude not in (8, 16) or period not in (128, 256, 512):
        raise ValueError('Curvature is outside the protected augmentation set')
    if not np.isfinite(phase):
        raise ValueError('Phase must be finite')
    return (amplitude * np.sin(2 * np.pi * np.arange(WIDTH) / period + phase)).astype(np.float32)


def feasible_top(displace, ys=None, xs=None, warped=True):
    """Conservative source-supported top range, optionally retaining selected GT."""
    low, high = (16, 624) if warped else (0, 640)
    if ys is not None and len(ys):
        transformed = np.asarray(ys, np.float64) - displace[np.asarray(xs, int)]
        # One output-pixel margin avoids endpoint rounding losses in nearest
        # label sampling. This is TRAIN crop placement, not GT dilation.
        margin = 1 if warped else 0
        low = max(low, int(np.ceil(transformed.max() - (HEIGHT - 1 - margin))))
        high = min(high, int(np.floor(transformed.min() - margin)))
    return low, high


def paired_crop(image, truth, desired_top, *, curve=None, retain=None):
    if image.shape[:2] != (SOURCE_HEIGHT, WIDTH) or truth.shape != (SOURCE_HEIGHT, WIDTH):
        raise ValueError('Expected actual 1280H x512W projected source pair')
    if image.ndim != 3 or image.shape[2] != 3 or image.dtype != np.uint8:
        raise ValueError('Expected uint8 BGR source')
    if not np.isfinite(desired_top) or not set(np.unique(truth)) <= {0, 1}:
        raise ValueError('Expected finite placement and binary actual occupancy')
    keep_y, keep_x = retain if retain is not None else (None, None)
    requested = curve is not None
    f = displacement(*curve) if requested else np.zeros(WIDTH, np.float32)
    low, high = feasible_top(f, keep_y, keep_x, requested)
    fallback = None
    if low > high:
        fallback = 'selected_positive_cannot_fit_observed_curved_geometry'
        f = np.zeros(WIDTH, np.float32)
        low, high = feasible_top(f, keep_y, keep_x, False)
    if low > high:
        raise ValueError('Selected identity positive cannot fit the declared native crop')
    top = int(np.clip(np.floor(desired_top), low, high))
    map_y = np.arange(HEIGHT, dtype=np.float32)[:, None] + top + f[None, :]
    map_x = np.broadcast_to(np.arange(WIDTH, dtype=np.float32), (HEIGHT, WIDTH)).copy()
    if float(map_y.min()) < 0 or float(map_y.max()) > SOURCE_HEIGHT - 1:
        raise AssertionError('Remapping requested unobserved source pixels')
    # Border constant is unreachable: bounds above are checked before remap.
    frame = cv2.remap(image, map_x, map_y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)
    target = cv2.remap(truth, map_x, map_y, cv2.INTER_NEAREST, borderMode=cv2.BORDER_CONSTANT)
    if retain is not None:
        # The source lookup generated by OpenCV itself verifies actual selected
        # occupancy survived nearest sampling; no morphology or fabricated GT.
        selected = np.zeros_like(truth)
        selected[np.asarray(keep_y, int), np.asarray(keep_x, int)] = 1
        mapped = cv2.remap(selected, map_x, map_y, cv2.INTER_NEAREST, borderMode=cv2.BORDER_CONSTANT)
        if int(mapped.sum()) != len(keep_y):
            raise AssertionError('Selected positive occupancy was lost during paired remapping')
    return frame, target, {
        'requested_curve': requested, 'applied_curve': requested and fallback is None,
        'identity_fallback': fallback, 'curve': list(curve) if requested else None,
        'top': top, 'feasible_top': [low, high],
        'sampled_source_y_min': float(map_y.min()), 'sampled_source_y_max': float(map_y.max()),
        'selected_source_pixels': 0 if keep_y is None else len(keep_y),
        'output_positive_pixels': int(target.sum()),
    }


def select_component(truth, point_y, point_x):
    """Return the entire actual 8-connected TRAIN component at a sampled pixel."""
    _, labels = cv2.connectedComponents(truth, connectivity=8)
    label = int(labels[int(point_y), int(point_x)])
    if not label:
        raise ValueError('Selected positive is not actual source GT')
    return np.nonzero(labels == label)


def training_arrays(rows, sdd2, rng, hard, step):
    slot = (step - 1) % 5
    rehearsal = slot == 4
    if rehearsal:
        positive = ((step // 5) % 2) == 1
        pool = sdd2.positive if positive else sdd2.normal
        image, truth, ys, xs, name = sdd2.get(pool[int(rng.integers(len(pool)))])
        role = 'positive' if positive else 'normal'
    else:
        role = ['positive', 'positive', 'hard', 'unbiased'][slot]
        pool = ([row for row in rows if len(row[2])] if role == 'positive' else
                [row for row in rows if hard.get(row[4])] if role == 'hard' else rows)
        image, truth, ys, xs, name = pool[int(rng.integers(len(pool)))]
    retain = None
    if role == 'positive':
        point = int(rng.integers(len(ys)))
        cy = float(ys[point]) + rng.uniform(-.3, .3) * HEIGHT
        retain = (ys[point:point + 1], xs[point:point + 1]) if rehearsal else select_component(truth, ys[point], xs[point])
    elif role == 'hard':
        point = hard[name][int(rng.integers(len(hard[name])))]
        cy = point['y'] + rng.uniform(-.125, .125) * HEIGHT
    else:
        cy = rng.uniform(320, 960)
    # Identical Bernoulli probability for every role, including true normals.
    curve = (int(rng.choice([8, 16])), int(rng.choice([128, 256, 512])), float(rng.uniform(0, 2 * np.pi))) if rng.random() < .5 else None
    frame, target, info = paired_crop(image, truth, cy - 320, curve=curve, retain=retain)
    if rng.random() < .5:
        frame, target = frame[::-1, ::-1], target[::-1, ::-1]
    if rng.random() < .5:
        frame, target = frame[:, ::-1], target[:, ::-1]
    frame = np.clip((frame.astype(np.float32) - 127.5) * rng.uniform(.4, 1.4)
                    + 127.5 + rng.uniform(-30, 30), 0, 255)
    if rng.random() < .15:
        frame = cv2.GaussianBlur(frame, (3, 3), float(rng.uniform(.3, .8)))
    info.update(role=role, source=name, rehearsal=rehearsal)
    return frame.astype(np.uint8), target, info
